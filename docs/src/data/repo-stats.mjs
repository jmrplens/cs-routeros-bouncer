import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { getLatestRelease } from "../lib/latest-release.mjs";

/**
 * Build-time facts about this repository, each derived from the file that
 * actually asserts it.
 *
 * The landing page used to restate the same handful of numbers — the supported
 * CrowdSec floor, the RouterOS generation, the per-operation latency — once in
 * the JSON-LD block, once in the feature cards and once in the prose, times two
 * locales. Four copies of a fact drift into three different facts: a bump to
 * the supported version floor had to be made in four places or the page would
 * contradict its own structured data.
 *
 * Every export below names the file it is read from. Nothing here is a literal
 * copied from prose, with the single documented exception of the CrowdSec and
 * RouterOS requirement pair, which has no machine-readable assertion anywhere
 * in the repository and is therefore parsed from the one place that does state
 * it — the README's "Requirements" section.
 *
 * Failures are loud on purpose. Every read and every parse throws with the file
 * and the shape it expected, so a refactor that moves a source file breaks the
 * build instead of quietly rendering an empty span. This project has shipped a
 * vacuous fact three times; a thrown error is the cheapest place to stop the
 * fourth.
 */

/**
 * Resolve the repository root.
 *
 * `src/lib/latest-release.mjs` documents the trap this has to avoid: the Astro
 * CLI runs with `docs/` as its working directory, but modules that get bundled
 * (a Head override, an island) execute from `dist/`, where `import.meta.url` no
 * longer points anywhere near the source tree. So cwd is tried first and the
 * `import.meta.url` walk is only the last resort. Each candidate is confirmed
 * by the presence of `go.mod`, so a wrong guess can never silently win.
 * @returns {string} absolute path to the repository root
 */
function resolveRepoRoot() {
	const candidates = [
		// `astro build` / `astro dev`, whose cwd is the docs package.
		path.resolve(process.cwd(), ".."),
		// A build invoked from the repository root.
		process.cwd(),
		// Unbundled execution (node, vitest, `astro check`): walk up from here.
		fileURLToPath(new URL("../../..", import.meta.url)),
	];
	for (const candidate of candidates) {
		if (existsSync(path.join(candidate, "go.mod"))) return candidate;
	}
	throw new Error(
		`repo-stats.mjs: could not locate the repository root (no go.mod in any of: ${candidates.join(", ")}). ` +
			"Every fact on the landing page is derived from files at that root, so the build cannot continue.",
	);
}

const REPO_ROOT = resolveRepoRoot();

/**
 * Read a repository file, failing loudly rather than yielding an empty string.
 * @param {string} relativePath path relative to the repository root
 * @returns {string} file contents
 */
function readSource(relativePath) {
	const absolute = path.join(REPO_ROOT, relativePath);
	let contents;
	try {
		contents = readFileSync(absolute, "utf-8");
	} catch (cause) {
		throw new Error(
			`repo-stats.mjs: cannot read ${relativePath} (looked at ${absolute}). ` +
				"The landing page derives its facts from this file; fix the path instead of hardcoding the value.",
			{ cause },
		);
	}
	if (contents.trim() === "") {
		throw new Error(
			`repo-stats.mjs: ${relativePath} is empty, so nothing can be derived from it.`,
		);
	}
	return contents;
}

/**
 * Apply a regular expression that is expected to match exactly once, and return
 * its capture groups. A miss means the source file changed shape.
 * @param {string} contents file contents
 * @param {RegExp} pattern pattern with at least one capture group
 * @param {string} relativePath file the contents came from, for the message
 * @param {string} what human-readable name of the fact being extracted
 * @returns {RegExpExecArray} the match
 */
function matchOrThrow(contents, pattern, relativePath, what) {
	const match = pattern.exec(contents);
	if (!match) {
		throw new Error(
			`repo-stats.mjs: could not find ${what} in ${relativePath} (pattern ${pattern}). ` +
				"The file's shape changed; update the parser rather than pasting the value in prose.",
		);
	}
	return match;
}

