const GO_MOD = "go.mod";
const README = "README.md";
const GORELEASER = ".goreleaser.yaml";
// Committed artefact generated by `scripts/extract-config-schema.mjs` from
// `internal/config/config.go` and gated by `pnpm run config:check`. The
// extractor's contract is explicit that the Astro build reads the JSON and
// never parses Go, so the defaults are taken from here rather than re-parsing
// `v.SetDefault(...)` a second time.
const CONFIG_SCHEMA = "docs/src/data/config-schema.json";
// The page that documents measured operation costs, each stated with the
// hardware and list size it was taken on. Measurements belong here rather than
// in the README, which states no conditions and which nothing gates.
const BENCHMARKING = "docs/src/content/docs/development/benchmarking.mdx";

// ---------------------------------------------------------------------------
// Minimal YAML helpers
//
// `.goreleaser.yaml` is the only YAML that has to be read here and the docs
// package has no YAML parser (adding one to render four platform names is not
// a trade worth making). The shapes below — a block of scalar list items and a
// list of two-key maps — are stable under any formatter, and both helpers throw
// on a miss, so a degraded parse cannot produce a plausible-looking subset.
// ---------------------------------------------------------------------------

/**
 * Return the indented body of a `key:` block.
 * @param {string} contents YAML text
 * @param {string} key key whose block body is wanted
 * @param {string} relativePath file the contents came from, for the message
 * @returns {string} the block body, with its own indentation intact
 */
function yamlBlock(contents, key, relativePath) {
	const header = matchOrThrow(
		contents,
		new RegExp(String.raw`^([ \t]*)${key}:[ \t]*$`, "m"),
		relativePath,
		`the \`${key}:\` block`,
	);
	const indent = header[1].length;
	const lines = contents.slice(header.index + header[0].length).split("\n");
	const body = [];
	for (const line of lines) {
		const isBlank = line.trim() === "";
		const isComment = line.trim().startsWith("#");
		if (!isBlank && !isComment) {
			const lineIndent = line.length - line.trimStart().length;
			if (lineIndent <= indent) break;
		}
		body.push(line);
	}
	return body.join("\n");
}

/**
 * Read a block of scalar list items (`- linux`, `- "386"`).
 * @param {string} contents YAML text
 * @param {string} key key holding the list
 * @param {string} relativePath file the contents came from, for the message
 * @returns {string[]} the items, unquoted, in file order
 */
function yamlList(contents, key, relativePath) {
	const body = yamlBlock(contents, key, relativePath);
	const items = [];
	for (const line of body.split("\n")) {
		// Parsed with string operations rather than a pattern. Every regex shape
		// for "dash, whitespace, rest of line" puts two whitespace-matching
		// pieces next to each other, and the engine can backtrack over how the
		// run between them is split. Slicing is unambiguous by construction,
		// obviously linear, and says what it does.
		const trimmed = line.trim();
		if (!trimmed.startsWith("-")) continue;
		const rest = trimmed.slice(1);
		// A bare `-` opens a nested block, and `-foo` is not a list item at all;
		// only `- value` is. Preserves the previous pattern's `[ \t]+`.
		if (!rest.startsWith(" ") && !rest.startsWith("\t")) continue;
		const value = rest.trim();
		if (value !== "") {
			items.push(value.replace(/^["']|["']$/g, ""));
		}
	}
	if (items.length === 0) {
		throw new Error(
			`repo-stats.mjs: the \`${key}:\` list in ${relativePath} parsed as empty.`,
		);
	}
	return items;
}

