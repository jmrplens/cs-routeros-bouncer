/**
 * The Go version this module targets, exactly as the `go` directive states it.
 *
 * Source: the `go` directive in `go.mod`.
 * @type {string}
 */
export const goVersion = matchOrThrow(
	goMod,
	/^go[ \t]+(\d+\.\d+(?:\.\d+)?)[ \t]*$/m,
	GO_MOD,
	"the `go` directive",
)[1];

/**
 * The same Go version trimmed to `major.minor`, for prose that reads
 * "Go 1.27+" rather than "Go 1.27.0+".
 *
 * Source: derived from {@link goVersion}.
 * @type {string}
 */
export const goVersionMajorMinor = goVersion.split(".").slice(0, 2).join(".");

/**
 * The version of the CrowdSec module the bouncer compiles against.
 *
 * Source: the `github.com/crowdsecurity/crowdsec` require line in `go.mod`.
 *
 * This is the library it links, NOT the oldest CrowdSec server it supports —
 * see {@link crowdsecMinVersion} for that. Do not render the two as the same
 * claim.
 * @type {string}
 */
export const crowdsecLibraryVersion = matchOrThrow(
	goMod,
	/^[ \t]*github\.com\/crowdsecurity\/crowdsec[ \t]+v(\d+\.\d+\.\d+)[ \t]*$/m,
	GO_MOD,
	"the github.com/crowdsecurity/crowdsec require line",
)[1];

const readme = readSource(README);

/**
 * The "## Requirements" section of the README, isolated so the version patterns
 * below cannot accidentally match a number from the benchmark tables further
 * down the file.
 */
const readmeRequirements = matchOrThrow(
	readme,
	/^## Requirements[ \t]*$([\s\S]*?)^## /m,
	README,
	"the `## Requirements` section",
)[1];

/**
 * The oldest CrowdSec release this bouncer supports, as a bare version — render
 * it as `${crowdsecMinVersion}+`, the "+" is not part of the value.
 *
 * Source: the "**CrowdSec** 1.5+ with LAPI…" bullet under `## Requirements` in
 * `README.md`.
 *
 * NOTE: this floor has no machine-readable assertion anywhere in the
 * repository. The bouncer speaks the LAPI through `go-cs-bouncer` and never
 * version-gates it, and CI does not run a matrix of CrowdSec versions, so
 * nothing in the code or the workflows encodes it. The README bullet is the
 * one place the project commits to it, so it is parsed from there: still a
 * single source of truth, just a prose one.
 * @type {string}
 */
export const crowdsecMinVersion = matchOrThrow(
	readmeRequirements,
	/^-[ \t]+\*\*CrowdSec\*\*[ \t]+(\d+\.\d+)\+/m,
	README,
	"the minimum CrowdSec version bullet",
)[1];

/**
 * The RouterOS generation supported, e.g. `7.x`.
 *
 * Source: the "**MikroTik RouterOS** 7.x with API enabled…" bullet under
 * `## Requirements` in `README.md`.
 *
 * Same caveat as {@link crowdsecMinVersion}: the RouterOS API client
 * (`go-routeros/routeros/v3`) carries a library major version, not a RouterOS
 * one, and nothing in the code inspects the router's version, so the README
 * bullet is the only assertion in the repository.
 * @type {string}
 */
export const routerosGeneration = matchOrThrow(
	readmeRequirements,
	/^-[ \t]+\*\*MikroTik RouterOS\*\*[ \t]+(\d+\.x)\b/m,
	README,
	"the RouterOS generation bullet",
)[1];

/**
 * Median latency of an individual ban write to the RouterOS API.
 *
 * Source: the "Cache-first optimistic add" row of the real-world results table
 * in `development/benchmarking.mdx`. `label` is the table's own rendering (en
 * dash, tilde); `min`, `max` and `unit` are there so prose can phrase it
 * differently — "about 1-3 ms" in a sentence, "~1–3 ms/op" in a card title —
 * without either copy being typed by hand.
 *
 * This used to parse the README's benchmark table. That table was removed:
 * every figure in it was stated without the hardware or list size it came from,
 * and two of them were wrong — an unban was credited with a ~2 ms API call when
 * it measured 1,155 ms against 22,000 entries before the id cache landed, and
 * the rule count was four when a stock configuration writes eight. A number the
 * documentation site renders should be read from the page that states its
 * conditions and that CI builds, not from prose nothing checks.
 * @type {{ min: number, max: number, unit: string, approximate: boolean, label: string }}
 */
export const banLatency = (() => {
	const row = matchOrThrow(
		readSource(BENCHMARKING),
		/^\|[ \t]*Cache-first optimistic add[^|]*\|[ \t]*(~)?(\d+)[–-](\d+)[ \t]*(ms|s) per operation/m,
		BENCHMARKING,
		"the `Cache-first optimistic add` benchmark row",
	);
	const [, approx, min, max, unit] = row;
	return {
		min: Number(min),
		max: Number(max),
		unit,
		approximate: Boolean(approx),
		label: `${approx ?? ""}${min}–${max} ${unit}`,
	};
})();

/**
 * The CrowdSec decision types the bouncer acts on out of the box.
 *
 * Source: the `crowdsec.supported_decisions_types` default in
 * `internal/config/config.go` (`v.SetDefault(...)`), read through the committed
 * `src/data/config-schema.json` that `scripts/extract-config-schema.mjs`
 * generates from it and `pnpm run config:check` keeps in sync.
 * @type {string[]}
 */
export const supportedDecisionTypes = (() => {
	const raw = readSource(CONFIG_SCHEMA);
	let schema;
	try {
		schema = JSON.parse(raw);
	} catch (cause) {
		throw new Error(
			`repo-stats.mjs: ${CONFIG_SCHEMA} is not valid JSON. Run \`pnpm run config:extract\`.`,
			{ cause },
		);
	}
	const key = "crowdsec.supported_decisions_types";
	const value = schema?.options?.[key]?.default;
	if (!Array.isArray(value) || value.length === 0) {
		throw new Error(
			`repo-stats.mjs: \`${key}\` has no non-empty default in ${CONFIG_SCHEMA}. ` +
				"Either the extractor's shape changed or config.go stopped defaulting it; both need a human.",
		);
	}
	return value.map(String);
})();

/**
 * The platforms a release actually publishes.
 *
 * Source: `.goreleaser.yaml` — the `builds` entry's `goos`/`goarch` matrix
 * minus its `ignore` list (with `goarm` expanding each `arm` target into one
 * artefact per ARM version), and the `dockers_v2` entry's `platforms` list for
 * the container image.
 *
 * `binaries` maps each OS to the architectures built for it, in the file's own
 * order; `armVersions` lists the ARM variants those `arm` entries expand into;
 * `binaryCount` is the number of binaries a release produces, counting each ARM
 * variant separately, exactly as the archives do.
 * @type {{ operatingSystems: string[], binaries: Record<string, string[]>, armVersions: string[], binaryCount: number, docker: string[] }}
 */
export const releasePlatforms = (() => {
	const goreleaser = readSource(GORELEASER);
	const builds = yamlBlock(goreleaser, "builds", GORELEASER);

	const operatingSystems = yamlList(builds, "goos", GORELEASER);
	const architectures = yamlList(builds, "goarch", GORELEASER);
	const armVersions = yamlList(builds, "goarm", GORELEASER);

	// `ignore:` holds two-key maps whose entries share a line pair:
	//   - goos: windows
	//     goarch: arm
	const ignoreBlock = yamlBlock(builds, "ignore", GORELEASER);
	// Walked line by line rather than matched with one two-line pattern. The
	// combined regex reached a complexity of 22 for what is really two simple
	// lookups, and a reader had to hold both lines of YAML in their head to see
	// what it captured.
	const ignored = new Set();
	let pendingGoos = null;
	for (const line of ignoreBlock.split("\n")) {
		const goos = /^[ \t]*-[ \t]*goos:[ \t]*["']?([\w-]+)["']?/.exec(line);
		if (goos) {
			pendingGoos = goos[1];
			continue;
		}
		const goarch = /^[ \t]*goarch:[ \t]*["']?([\w-]+)["']?/.exec(line);
		if (goarch && pendingGoos !== null) {
			ignored.add(`${pendingGoos}/${goarch[1]}`);
			pendingGoos = null;
		}
	}
	if (ignored.size === 0) {
		throw new Error(
			`repo-stats.mjs: the \`ignore:\` list in ${GORELEASER} parsed as empty, ` +
				"which would advertise architectures the release does not publish.",
		);
	}

	/** @type {Record<string, string[]>} */
	const binaries = {};
	let binaryCount = 0;
	for (const goos of operatingSystems) {
		const built = architectures.filter(
			(goarch) => !ignored.has(`${goos}/${goarch}`),
		);
		if (built.length === 0) {
			throw new Error(
				`repo-stats.mjs: every architecture is ignored for \`${goos}\` in ${GORELEASER}; ` +
					"the parse is wrong or the build matrix is.",
			);
		}
		binaries[goos] = built;
		binaryCount += built.reduce(
			(total, goarch) => total + (goarch === "arm" ? armVersions.length : 1),
			0,
		);
	}

	const dockers = yamlBlock(goreleaser, "dockers_v2", GORELEASER);
	const docker = yamlList(dockers, "platforms", GORELEASER);

	return { operatingSystems, binaries, armVersions, binaryCount, docker };
})();
